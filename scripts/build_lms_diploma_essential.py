    doc = word.Documents.Open(str(path), ReadOnly=True)
    doc.Repaginate()
    pages = doc.ComputeStatistics(wdStatisticPages)
    headings = []
    for index in range(1, doc.Paragraphs.Count + 1):
        rng = doc.Paragraphs.Item(index).Range
        text = rng.Text.replace("\r", " ").replace("\a", " ").strip()
        if not text:
            continue
        try:
            style = rng.Style.NameLocal
        except Exception:
            style = str(rng.Style)
        if style.startswith("Заголовок") or text.startswith("ГЛАВА ") or text in {"СОДЕРЖАНИЕ", "СПИСОК ИСПОЛЬЗОВАННЫХ ИСТОЧНИКОВ"}:
            headings.append((rng.Information(3), style, text[:140]))
    doc.Close(False)
    word.Quit()
    return pages, headings


