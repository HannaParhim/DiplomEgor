def add_heading(selection, text: str, style: str, align: int, bold: bool = False, font_size: int = 14, first_indent_cm: float | None = 1.25):
    selection.EndKey(Unit=6)
    selection.Style = style
    selection.Font.Name = "Times New Roman"
    selection.Font.Size = font_size
    selection.Font.Bold = -1 if bold else 0
    selection.ParagraphFormat.Alignment = align
    selection.ParagraphFormat.LeftIndent = 0
    selection.ParagraphFormat.RightIndent = 0
    selection.ParagraphFormat.SpaceBefore = 0
    selection.ParagraphFormat.SpaceAfter = 0
    selection.ParagraphFormat.LineSpacingRule = wdLineSpace1pt5
    selection.ParagraphFormat.FirstLineIndent = cm(first_indent_cm) if first_indent_cm is not None else 0
    if text:
        selection.TypeText(text)
    selection.TypeParagraph()
    selection.Font.Bold = 0


def build_document(assets, chapter_1, chapter_2, sources):
    word = win32com.client.DispatchEx("Word.Application")
    word.Visible = False
    word.DisplayAlerts = 0
    doc = word.Documents.Open(str(WORK_FILE))
    doc.Activate()
    doc.Range(0, doc.Content.End - 1).Delete()

    doc.PageSetup.TopMargin = cm(2.0)
    doc.PageSetup.BottomMargin = cm(2.0)
    doc.PageSetup.LeftMargin = cm(3.0)
    doc.PageSetup.RightMargin = cm(1.0)
    doc.PageSetup.HeaderDistance = cm(1.25)
    doc.PageSetup.FooterDistance = cm(1.25)

    sel = word.Selection

    def add_paragraph(text="", style=STYLE_BODY, align=wdAlignParagraphJustify, bold=False, first_indent_cm=1.25, font_size=14):
        add_heading(sel, text, style, align, bold=bold, font_size=font_size, first_indent_cm=first_indent_cm)

    def add_chapter(number, title):
        add_paragraph(f"ГЛАВА {number}", style=STYLE_BODY, align=wdAlignParagraphCenter, bold=True, first_indent_cm=0, font_size=15)
        add_paragraph(title, style=STYLE_H1, align=wdAlignParagraphCenter, bold=True, first_indent_cm=0, font_size=15)

    def add_figure(chapter_number, caption_number, asset_key, caption_text, note_text, width_cm=None):
        sel.EndKey(Unit=6)
        sel.Style = STYLE_BODY
        sel.ParagraphFormat.Alignment = wdAlignParagraphCenter
        sel.ParagraphFormat.FirstLineIndent = 0
        pic = sel.InlineShapes.AddPicture(str(assets[asset_key]))
        pic.LockAspectRatio = True
        pic.Width = cm(width_cm or (13.0 if str(asset_key).startswith("screen_") else 16.6))
        sel.TypeParagraph()
        add_paragraph(f"Рисунок {chapter_number}.{caption_number} – {caption_text}", style=STYLE_BODY, align=wdAlignParagraphCenter, first_indent_cm=0, font_size=12)
        add_paragraph(note_text, style=STYLE_BODY, align=wdAlignParagraphLeft, first_indent_cm=0, font_size=12)

    def add_table(chapter_number, caption_number, caption_text, headers, rows, note_text):
        add_paragraph(f"Таблица {chapter_number}.{caption_number} – {caption_text}", style=STYLE_BODY, align=wdAlignParagraphLeft, first_indent_cm=0, font_size=12)
        sel.EndKey(Unit=6)
        rng = doc.Range(doc.Content.End - 1, doc.Content.End - 1)
        table = doc.Tables.Add(rng, len(rows) + 1, len(headers))
        table.Borders.Enable = True
        table.Rows(1).Range.Font.Bold = True
        table.Range.Font.Name = "Times New Roman"
        table.Range.Font.Size = 12
        table.Range.ParagraphFormat.Alignment = wdAlignParagraphCenter
        for col, header in enumerate(headers, start=1):
            table.Cell(1, col).Range.Text = str(header)
        for row_idx, row in enumerate(rows, start=2):
            for col_idx, value in enumerate(row, start=1):
                table.Cell(row_idx, col_idx).Range.Text = str(value)
        try:
            table.AutoFitBehavior(1)
        except Exception:
            pass
        doc.Range(table.Range.End, table.Range.End).InsertParagraphAfter()
        add_paragraph(note_text, style=STYLE_BODY, align=wdAlignParagraphLeft, first_indent_cm=0, font_size=12)

    def page_break():
        sel.EndKey(Unit=6)
        sel.InsertBreak(wdPageBreak)

    def add_sections(sections, chapter_number):
        figure_no = 0
        table_no = 0
        for heading, items in sections:
            add_paragraph(heading, style=STYLE_H2, align=wdAlignParagraphLeft, bold=True, first_indent_cm=0, font_size=14)
            for kind, *payload in items:
                if kind == "p":
                    add_paragraph(payload[0])
                elif kind == "list":
                    add_paragraph(payload[0], style=STYLE_LIST, align=wdAlignParagraphLeft, first_indent_cm=1.25, font_size=14)
                elif kind == "figure":
                    figure_no += 1
                    width_cm = payload[3] if len(payload) > 3 else None
                    add_figure(chapter_number, figure_no, payload[0], payload[1], payload[2], width_cm)
                elif kind == "table":
                    table_no += 1
                    add_table(chapter_number, table_no, payload[0], payload[1], payload[2], payload[3])

    add_paragraph("СОДЕРЖАНИЕ", style=STYLE_BODY, align=wdAlignParagraphCenter, bold=True, first_indent_cm=0, font_size=15)
    sel.EndKey(Unit=6)
    toc_range = doc.Range(doc.Content.End - 1, doc.Content.End - 1)
    doc.TablesOfContents.Add(toc_range, True, 1, 2)
    sel.EndKey(Unit=6)
    sel.TypeParagraph()
    page_break()

    add_chapter(1, "АНАЛИТИЧЕСКАЯ ЧАСТЬ")
    add_sections(chapter_1, 1)
    page_break()
    add_chapter(2, "ПРОЕКТНАЯ ЧАСТЬ")
    add_sections(chapter_2, 2)
    page_break()
    add_paragraph("СПИСОК ИСПОЛЬЗОВАННЫХ ИСТОЧНИКОВ", style=STYLE_H1, align=wdAlignParagraphCenter, bold=True, first_indent_cm=0, font_size=15)
    for source in sources:
        add_paragraph(source, style=STYLE_LIST, align=wdAlignParagraphLeft, first_indent_cm=1.25, font_size=14)

    if doc.TablesOfContents.Count > 0:
        doc.TablesOfContents(1).Update()
    doc.Fields.Update()
    doc.Repaginate()
    pages = doc.ComputeStatistics(wdStatisticPages)
    doc.Save()
    doc.Close(False)
    word.Quit()
    return pages


