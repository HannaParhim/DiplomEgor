def text_lines(x: int, y: int, lines, css: str = "text", anchor: str = "start", step: int = 23) -> str:
    safe = [escape(str(line)) for line in lines]
    spans = [f'<tspan x="{x}" dy="0">{safe[0]}</tspan>']
    for line in safe[1:]:
      spans.append(f'<tspan x="{x}" dy="{step}">{line}</tspan>')
    return f'<text x="{x}" y="{y}" text-anchor="{anchor}" class="{css}">{"".join(spans)}</text>'


def box(x: int, y: int, w: int, h: int, title: str, lines=(), fill_cls: str = "box") -> str:
    title_safe = escape(title)
    body = []
    if title:
        body.append(f'<rect x="{x}" y="{y}" width="{w}" height="34" class="header"/>')
        body.append(f'<text x="{x + w/2}" y="{y + 23}" text-anchor="middle" class="subtitle">{title_safe}</text>')
    if lines:
        body.append(text_lines(x + 18, y + 58, lines, css="text"))
    return f'<rect x="{x}" y="{y}" width="{w}" height="{h}" class="{fill_cls}"/>' + "".join(body)


def ellipse(cx: int, cy: int, rx: int, ry: int, title: str) -> str:
    return (
        f'<ellipse cx="{cx}" cy="{cy}" rx="{rx}" ry="{ry}" class="oval"/>'
        f'<text x="{cx}" y="{cy+6}" text-anchor="middle" class="text">{escape(title)}</text>'
    )


def path(points, arrow: bool = False, dashed: bool = False) -> str:
    cls = "arrow" if arrow else "line"
    if dashed:
        cls += " dash"
    formatted = " ".join(f"{x},{y}" for x, y in points)
    return f'<polyline points="{formatted}" class="{cls}"/>'


def note(text: str, y: int, x: int = 70) -> str:
    return ""


def actor(x: int, y: int, label: str) -> str:
    return "\n".join(
        [
            f'<circle cx="{x}" cy="{y}" r="14" class="line"/>',
            path([(x, y + 14), (x, y + 58)]),
            path([(x - 28, y + 30), (x + 28, y + 30)]),
            path([(x, y + 58), (x - 24, y + 98)]),
            path([(x, y + 58), (x + 24, y + 98)]),
            text_lines(x, y + 126, [label], css="text", anchor="middle"),
        ]
    )


def ellipse_text(cx: int, cy: int, rx: int, ry: int, lines) -> str:
    if isinstance(lines, str):
        lines = [lines]
    return (
        f'<ellipse cx="{cx}" cy="{cy}" rx="{rx}" ry="{ry}" class="oval"/>'
        + text_lines(cx, cy - (10 if len(lines) > 1 else -6), lines, css="text", anchor="middle", step=20)
    )


def dot(x: int, y: int, r: int = 9) -> str:
    return f'<circle cx="{x}" cy="{y}" r="{r}" fill="#111827"/>'


def swimlane_diagram(lanes, steps, arrows, key: str, height: int = 820):
    left = 70
    top = 90
    lane_label_w = 220
    lane_h = 165
    body_parts = [
        f'<rect x="{left}" y="{top}" width="1230" height="{lane_h * len(lanes)}" class="box"/>',
        f'<line x1="{left + lane_label_w}" y1="{top}" x2="{left + lane_label_w}" y2="{top + lane_h * len(lanes)}" class="line"/>',
    ]

    for idx, lane_name in enumerate(lanes):
        y = top + idx * lane_h
        if idx:
            body_parts.append(f'<line x1="{left}" y1="{y}" x2="{left + 1230}" y2="{y}" class="line"/>')
        body_parts.append(text_lines(left + lane_label_w // 2, y + lane_h // 2, lane_name.split("\n"), css="subtitle", anchor="middle", step=24))

    nodes = {}
    for step_id, lane_idx, x, w, lines in steps:
        y = top + lane_idx * lane_h + 46
        h = 74
        body_parts.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" class="panel"/>')
        body_parts.append(text_lines(x + w // 2, y + 28, lines, css="text", anchor="middle", step=22))
        nodes[step_id] = (x, y, w, h)

    def edge_point(node, side):
        x, y, w, h = node
        if side == "r":
            return (x + w, y + h // 2)
        if side == "l":
            return (x, y + h // 2)
        if side == "t":
            return (x + w // 2, y)
        return (x + w // 2, y + h)

    for from_id, to_id, from_side, to_side in arrows:
        start = edge_point(nodes[from_id], from_side)
        end = edge_point(nodes[to_id], to_side)
        mid_x = (start[0] + end[0]) // 2
        if start[1] == end[1]:
            body_parts.append(path([start, end], arrow=True))
        elif start[0] == end[0]:
            body_parts.append(path([start, end], arrow=True))
        else:
            body_parts.append(path([start, (mid_x, start[1]), (mid_x, end[1]), end], arrow=True))

    assets = {}
    assets[key] = write_file(SVG_DIR / f"{key}.svg", svg_doc(key, "\n".join(body_parts), height=height))
    return assets


