def ensure_template():
    if not SAMPLE_SRC.exists():
        raise FileNotFoundError(f"Не найден файл-шаблон: {SAMPLE_SRC}")
    for path in [SAMPLE_TEMPLATE, WORK_FILE, REPAIRED_FILE]:
        try:
            if path.exists():
                path.unlink()
        except Exception:
            pass
    shutil.copy2(SAMPLE_SRC, SAMPLE_TEMPLATE)
    shutil.copy2(SAMPLE_TEMPLATE, WORK_FILE)


